#!/usr/bin/env python3
"""Render the PrometheusRule CRD's spec into a plain Prometheus rules file.

    scripts/render-rules.py            # write observability/prometheus/rules.generated.yml
    scripts/render-rules.py --check    # exit 1 if the generated file is stale (CI)

One source of truth (k8s/monitoring/prometheus-rule.yaml) for both the
Kubernetes and the Compose Prometheus, so an alert fixed in one is fixed in
both.
"""

import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "k8s/monitoring/prometheus-rule.yaml"
TARGET = ROOT / "observability/prometheus/rules.generated.yml"
HEADER = "# GENERATED by scripts/render-rules.py from k8s/monitoring/prometheus-rule.yaml. Do not edit.\n"


def render() -> str:
    spec = yaml.safe_load(SOURCE.read_text())["spec"]
    return HEADER + yaml.safe_dump(spec, sort_keys=False, width=1000)


def main() -> None:
    rendered = render()
    if "--check" in sys.argv:
        if not TARGET.exists() or TARGET.read_text() != rendered:
            sys.exit(f"{TARGET.relative_to(ROOT)} is stale: run scripts/render-rules.py")
        return
    TARGET.write_text(rendered)
    print(f"wrote {TARGET.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
